"""Typed contracts for Pricing & Negotiation agent."""

from __future__ import annotations

from typing import Literal
from uuid import UUID, uuid4

from pydantic import BaseModel, ConfigDict, Field

from stubbleos.core.types import LandholdingClass, ServiceType


class TariffQuote(BaseModel):
    """Quoted service tariff structure with equity breakdown and three-way settlement."""

    model_config = ConfigDict(extra="forbid")

    base_rate_inr: float = Field(..., gt=0.0)
    subsidy_discount_inr: float = Field(0.0, ge=0.0)
    surge_amount_inr: float = Field(0.0, ge=0.0)
    moisture_penalty_inr: float = Field(0.0, ge=0.0)
    net_price_inr: float = Field(..., ge=0.0)
    rationale: str
    operator_receivable_inr: float | None = None
    logistics_share_inr: float | None = None
    platform_fee_inr: float | None = None


class PricingInput(BaseModel):
    """Input parameters to generate a tariff quote."""

    model_config = ConfigDict(extra="forbid")

    farmer_id: UUID
    field_id: UUID
    landholding_class: LandholdingClass
    service_type: ServiceType
    area_acres: float = Field(..., gt=0.0)
    estimated_tonnes: float | None = None
    moisture_pct: float | None = None
    days_to_deadline: int | None = None
    machine_scarcity_ratio: float = 1.0


class PricingOutput(BaseModel):
    """Evaluated price quote."""

    model_config = ConfigDict(extra="forbid")

    quote: TariffQuote
    is_concessional: bool
    confidence: float = 1.0


class BiomassOffer(BaseModel):
    """Offer submitted by industrial biomass buyer."""

    model_config = ConfigDict(extra="forbid")

    buyer_id: UUID
    order_id: UUID
    proposed_price_per_tonne_inr: float = Field(..., gt=0.0)
    tonnes: float = Field(..., gt=0.0)
    delivery_term: Literal["ex_field", "cif_plant"] = "ex_field"
    moisture_max_pct: float = Field(14.0, ge=0.0, le=100.0)


class BiomassCounterOffer(BaseModel):
    """Response or counter-offer generated by StubbleOS negotiation engine."""

    model_config = ConfigDict(extra="forbid")

    buyer_id: UUID
    order_id: UUID
    round_number: int = 1
    counter_price_per_tonne_inr: float = Field(..., gt=0.0)
    accepted: bool = False
    walk_away: bool = False
    rationale: str


class ContractTermsDraft(BaseModel):
    """Cryptographically verifiable negotiated contract draft."""

    model_config = ConfigDict(extra="forbid")

    contract_id: UUID = Field(default_factory=uuid4)
    order_id: UUID | None = None
    field_id: UUID
    farmer_id: UUID
    buyer_id: UUID | None = None
    price_per_tonne_inr: float
    tonnes_agreed: float
    delivery_term: str = "ex_field"
    contract_sha256: str
    terms_summary: str


class PricingState(BaseModel):
    """LangGraph state for Pricing & Negotiation agent."""

    model_config = ConfigDict(extra="forbid")

    input: PricingInput
    output: PricingOutput | None = None
    status: str = "initialized"
    buyer_offer: BiomassOffer | None = None
    counter_offer: BiomassCounterOffer | None = None
    contract_draft: ContractTermsDraft | None = None
    negotiation_rounds: int = 0
